export const writeMessages: Record<Locale, WriteMessages> = { "zh-CN": zhCN, en };

export type WriteCopy = WriteMessages;

export function writeToolName(locale: Locale, name: string): string | undefined {
  if (name === "datanexa_submit_write") return writeMessages[locale].submitName;
  if (name === "datanexa_list_write_targets") return writeMessages[locale].targetsName;
  if (name === "datanexa_get_write_status") return writeMessages[locale].statusName;
  return undefined;
}

export function isWriteTool(name: string) {
  return name === "datanexa_submit_write" || name === "datanexa_get_write_status" || name === "datanexa_list_write_targets";
}

/** Reason codes the backend reports for a table that cannot be written. */
export function writeReasonText(locale: Locale, target: { reason_code?: string | null; reason?: string | null }): string {
  const copy = writeMessages[locale];
  switch (target.reason_code) {
    case "no_primary_key": return copy.reasonNoPrimaryKey;
    case "primary_key_nullable": return copy.reasonPrimaryKeyNullable;
    case "unsupported_column_type": return copy.reasonUnsupportedColumnType;
    case "no_writable_column": return copy.reasonNoWritableColumn;
    case "target_not_found": return copy.reasonTargetNotFound;
    case "not_a_base_table": return copy.reasonNotBaseTable;
    case "unsupported_engine": return copy.reasonUnsupportedEngine;
    case "unsupported_table_shape": return copy.reasonUnsupportedTableShape;
    case "row_level_security": return copy.reasonRowLevelSecurity;
    case "temporary_table": return copy.reasonTemporaryTable;
    case "rewrite_rule": return copy.reasonRewriteRule;
    default: return target.reason_code ? copy.reasonGeneric : "";
  }
}

/**
 * One tooltip line explaining why a table cannot be written. The backend's
 * `reason_detail` is identifiers and declared types only, so it is safe to show
 * as-is next to the localized reason.
 */
export function writeReasonDetail(locale: Locale, target: { reason_code?: string | null; reason?: string | null; reason_detail?: string | null }): string {
  const reason = writeReasonText(locale, target);
  return target.reason_detail ? `${reason} ${target.reason_detail}` : reason;
}

/** Localized warning text for the table-level facts carried by the backend. */
export function writeWarningText(locale: Locale, code: string): string {
  const copy = writeMessages[locale];
  switch (code) {
    case "triggers_present": return copy.warningTriggers;
    case "foreign_keys_present": return copy.warningForeignKeys;
    case "check_constraints_present": return copy.warningChecks;
    case "unique_constraints_present": return copy.warningUnique;
    case "text_primary_key": return copy.warningTextPrimaryKey;
    default: return code;
  }
}

export function writeErrorText(error: unknown): string {
  if (error instanceof Error) return error.message;
  if (typeof error === "string") return error;
  if (typeof error === "object" && error !== null) {
    // Metadata errors carry no row values. Only show diagnostic fields, never
    // stringify arbitrary request objects that could contain sensitive values.
    const record = error as Record<string, unknown>;
    return ["reason_code", "code", "sqlstate", "sql_state", "message", "reason"]
      .filter((key) => typeof record[key] === "string")
      .map((key) => `${key}: ${record[key]}`).join(" · ");
  }
  return "";
}
